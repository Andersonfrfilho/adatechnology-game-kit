import type { ArsenalBodyData } from './extract-arsenal-body'
import type { GameData } from './extract-game'
import type { LivingData, PortraitData } from './extract-living'
import type { Decisions } from './decisions'

const serialize = (data: unknown): string => `${JSON.stringify(data, null, 2)}\n`

export type SliceInputs = {
  readonly game: GameData
  readonly living: LivingData
  readonly portraits: PortraitData
  readonly arsenal: ArsenalBodyData
  readonly decisions: Decisions
}

const README = `# Game slice: characters

Generated by \`pnpm --filter @adatechnology/characters-catalog-tool catalog:game\` from the team deliveries (spec 001, Phase 4).
**This folder goes to the zombiada repository** (\`content/characters/\`), not to the SDK: it is content of one game (the valley, its
people and groups, 7º BIS, the life simulation, the calibre points table). The SDK keeps the generic parts
(\`game-characters\`, \`game-characters-people\`, \`game-characters-uniformed\`, \`game-characters-undead\`).

| File | What | Source |
|---|---|---|
| \`people.json\` | The 44 named people: appearance spec for the portrait builder, group, age line, item | Retratos do Vale \`PEOPLE\` |
| \`profiles.json\` | The same 44 people: age, occupation, history, personality, daily routine | Os Vivos do Vale \`NPCS\`, \`EXTRA\` |
| \`groups.json\` | The 18 groups with region, colour, defence and food | Os Vivos do Vale \`GROUPS\`, Retratos \`GC\` |
| \`relations.json\` | Relations, relation types, join rules, states, actions, risk by region | Os Vivos do Vale |
| \`events.json\` | The 47 day-by-day events | Os Vivos do Vale \`EV\` |
| \`forces.json\` | Factions (incl. 7º BIS), ranks, the rank rule, loot, generic troopers | Os Vivos do Vale \`FACT\`, \`RANKS\`, \`RANKRULE\`, \`LOOT\`, \`GENT\` |
| \`life-simulation.source.js\` | \`life\`, \`world\`, \`apply\`, \`simulate\` and their tables, verbatim (a game rule; not yet ported) | Os Vivos do Vale |
| \`points-table.json\` | Damage points per calibre of the game (the SDK default is \`3.5 * E^0.37\`) | jogo.js \`CALIBRES\` |
| \`zones.json\` | Where the game spawns its zones | jogo.js \`ZONES\` |
| \`sdk-mapping.json\` | Which SDK id each faction (\`eb\`, \`pm\`...) and each LOOT row became in \`game-characters-uniformed\`; \`null\` for the unique quest items the game keeps | decisions |
| \`block-characters.json\` | The characters of the starting block, including Seu Cícero and Sandra (Phase 8 roles) | jogo.js \`NPC\` |

How it lands in the zombiada repository: copy this folder to \`content/characters/\`; the game loads the SDK packs for the generic part and layers \`forces.json\`
(7º BIS and the named units) over them with \`sdk-mapping.json\`. \`profiles.json\` and \`people.json\` feed the portrait builder (\`game-characters-three\`) by id.

Cícero Tavares and Sandra Monteiro do not exist in the Retratos or in Os Vivos: they come from the game and become story roles (decision P9).
`

export const buildSlice = ({ game, living, portraits, arsenal, decisions }: SliceInputs): Readonly<Record<string, string>> => ({
  'README.md': README,
  'people.json': serialize(portraits.people),
  'profiles.json': serialize({ people: living.people, extra: living.extraPeople }),
  'groups.json': serialize({ groups: living.groups, colors: portraits.groupColors }),
  'relations.json': serialize({ relations: living.relations, types: living.relationTypes, joinRules: living.joinRules, states: living.states, actions: living.actions, risk: living.risk }),
  'events.json': serialize(living.events),
  'forces.json': serialize({ factions: living.factions, ranks: living.ranks, rankRule: living.rankRule, loot: living.loot, lootCategories: living.lootCategories, generics: living.generics }),
  'life-simulation.source.js': `${living.lifeSimulationSource}\n`,
  'points-table.json': serialize({ calibers: Object.fromEntries(Object.entries(game.calibers).map(([key, caliber]) => [decisions.calibreIds.value[key] ?? key, { name: caliber.nome, points: caliber.dano, ...(caliber.bagos === undefined ? {} : { pellets: caliber.bagos }) }])), weapons: arsenal.weapons }),
  'sdk-mapping.json': serialize({
    forces: Object.fromEntries(Object.entries(decisions.uniformedForces.value).map(([key, force]) => [key, force.id])),
    loot: Object.fromEntries((living.loot as readonly (readonly string[])[]).map((row) => [row[0], decisions.uniformedLootItems.value[row[0] ?? '']?.id ?? null])),
  }),
  'zones.json': serialize(game.zones),
  'block-characters.json': serialize(game.nonPlayerCharacters),
})
