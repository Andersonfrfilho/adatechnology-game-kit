const RELATION_KINDS: Readonly<Record<string, string>> = { fam: 'family', ali: 'trust', odio: 'hatred', seg: 'secret', medo: 'fear' }
const STATE_IDS: Readonly<Record<string, string>> = { ok: 'ok', ferido: 'hurt', mordido: 'bitten', zumbi: 'undead', morto: 'dead', sumido: 'missing', grupo: 'party', hostil: 'hostile', mudou: 'moved', partiu: 'left', nao: 'unborn' }

const sliceCast = (living: LivingData): unknown[] => {
  const T = living.lifeTables
  const women = new Set(T.women)
  const person = (n: Record<string, unknown>, extra: boolean) => {
    const id = String(n.id)
    const start = T.startUndead[id] !== undefined ? { state: STATE_IDS.zumbi, note: T.startUndead[id] } : n.born ? { state: STATE_IDS.nao, note: '' } : undefined
    return {
      id,
      name: n.n,
      ...(T.nicknames[id] ? { nick: T.nicknames[id] } : {}),
      ...(typeof n.i === 'number' ? { age: n.i } : {}),
      ...(women.has(id) ? { female: true } : {}),
      ...(Array.isArray(n.p) ? { personality: n.p } : {}),
      base: n.g,
      ...(start ? { start } : {}),
      ...(extra ? { extra: true } : {}),
    }
  }
  return [...living.people.map((n) => person(n, false)), ...living.extraPeople.map((n) => person(n, true))]
}

const living = (role: string) => ({ living: role })
const flag = (id: string) => ({ flag: id })

